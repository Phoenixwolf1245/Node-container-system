const assert=require('node:assert/strict');
const path=require('node:path');
const {tokenize}=require('./lib/highlight');
const catalog=require('./lib/catalog').load([path.join(__dirname,'nodes')]);
const boundary=require('./lib/comment-boundaries');
const ctx=require('./context');
const diag=require('./diagnostics');
const grammar=require('./syntaxes/ncs.tmLanguage.json');
const tm=grammar.repository.comments.patterns.find(x=>x.name==='comment.block.exclamation.ncs');
assert.equal(tm.match,boundary.inlinePattern);
const fallback=new RegExp(tm.match,'mu');
function check(src,comment,next,kind){
  const start=src.indexOf(comment), end=start+comment.length, after=src.indexOf(next,end);
  assert.ok(start>=0&&after>=end);
  const tokens=tokenize(src,catalog);
  const hit=tokens.find(t=>t.start===start);
  assert.deepEqual(hit,{start,end,kind:'comment'},src);
  assert.equal(tokens.find(t=>t.start<=after&&t.end>after)?.kind,kind,src);
  assert.equal(boundary.mask(src).slice(start,end),' '.repeat(comment.length));
  assert.equal(ctx.mask(src).length,src.length);
  assert.equal(diag.maskComments(src).slice(after,after+next.length),next);
  const match=fallback.exec(src);assert.equal(match[0],comment);
  assert.equal(boundary.inLiteralOrComment(src.slice(0,end)),false);
}
check('<count>!{note}42</int>','!{note}','42','number');
check('<count>!{Don\'t change this}42</int>',"!{Don't change this}",'42','number');
check('<message>!{It\'s a comment}"Hello"</str>',"!{It's a comment}",'"Hello"','string');
check('    !{a "}" in quotes}<next>2</int>','!{a "}" in quotes}','next','node');
check("<v>!{one '}' quoted}7</int>","!{one '}' quoted}",'7','number');
check('<v>!{unfinished " quote}7</int>','!{unfinished " quote}','7','number');
check('<v>!{first}!{second}7</int>','!{first}','7','number');
check('<v>1</int> !{middle} n%replace(2)','!{middle}','n%','variable');
check('<def:foo(v:int!{Don\'t omit},n:str)>',"!{Don't omit}",'str','signature');
assert.equal(ctx.definitions('<def:foo(v:int!{Don\'t omit},n:str)>\n</d>')[0].params[0].description,"Don't omit");
const text='<v>"!{not a comment}"</str> !<-- everything } after\n<next>5</int>\n"""doc !{still doc}\n""" <last>6</int>';
const tokens=tokenize(text,catalog);assert.equal(tokens.filter(x=>x.kind==='comment').length,1);assert.equal(tokens.filter(x=>x.kind==='doc').length,1);
for(const key of ['next','last'])assert.equal(tokens.find(x=>x.start===text.indexOf(key)).kind,'node');
const unfinished='<v>1</int> !{unfinished\n<next>2</int>';assert.ok(tokenize(unfinished,catalog).some(t=>t.kind==='node'&&t.start===unfinished.indexOf('next')));
assert.equal(boundary.inLiteralOrComment('!{unfinished'),true);assert.equal(boundary.inLiteralOrComment('!<-- line }'),true);assert.equal(boundary.inLiteralOrComment('!<-- line\n'),false);
assert.ok(diag.analyse('<v>!{Don\'t hide the error}3.14</int>',catalog.signatures).some(e=>e.code==='invalid-data'));
console.log('Inline comment boundaries, quoted braces, apostrophes, TextMate pattern, context and diagnostics passed');
